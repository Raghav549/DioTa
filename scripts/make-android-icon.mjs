/**
 * Generates the Android launcher icon from the DioTa wordmark: the real Fraunces glyphs, with the
 * same axes as the website (.dt-up: wght 700, opsz 144, SOFT 100 / .dt-it: italic, wght 340, opsz 144)
 * and the same colours (--w1..--w5), as vector paths in an adaptive icon.
 *
 *   npm i --no-save fontkit@2 wawoff2@2 && node scripts/make-android-icon.mjs
 *
 * Writes android/app/src/main/res/drawable/ic_launcher_foreground.xml and ic_launcher_monochrome.xml.
 * Pass --svg <file> to also write a preview SVG.
 */
import fs from "node:fs";
import path from "node:path";
import * as fontkit from "fontkit";
import wawoff2 from "wawoff2";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const files = path.join(root, "node_modules/@fontsource-variable/fraunces/files");
// fontkit can't instantiate variable WOFF2 fonts, so decompress to TrueType first.
const load = async (f) => fontkit.create(Buffer.from(await wawoff2.decompress(fs.readFileSync(path.join(files, f)))));
const upright = await load("fraunces-latin-full-normal.woff2");
const italic = await load("fraunces-latin-full-italic.woff2");

const UP = upright.getVariation({ wght: 700, opsz: 144, SOFT: 100, WONK: 1 });
const IT = italic.getVariation({ wght: 340, opsz: 144, SOFT: 0, WONK: 1 });
const LETTERS = [
  ["D", upright, UP],
  ["i", italic, IT],
  ["o", italic, IT],
  ["T", upright, UP],
  ["a", italic, IT],
];
const COLORS = ["#8b35de", "#c2299f", "#e0524d", "#d68a0b", "#12905a"]; // --w1..--w5 (light theme)

const em = upright.unitsPerEm;
const pad = 0.012 * em; // .dt-letter padding (each side)
const spacing = -0.02 * em; // .dt-word letter-spacing

// Lay out the word in font units (y up).
let x = 0;
const parts = [];
for (const [ch, , instance] of LETTERS) {
  const g = instance.glyphForCodePoint(ch.codePointAt(0));
  parts.push({ path: g.path, x: x + pad });
  x += g.advanceWidth + 2 * pad + spacing;
}
let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
for (const p of parts) {
  const b = p.path.bbox;
  minX = Math.min(minX, p.x + b.minX);
  maxX = Math.max(maxX, p.x + b.maxX);
  minY = Math.min(minY, b.minY);
  maxY = Math.max(maxY, b.maxY);
}

// Fit into the adaptive-icon safe zone (centre 66dp circle of the 108dp canvas).
const VIEW = 108;
const targetW = 62;
const s = targetW / (maxX - minX);
const h = (maxY - minY) * s;
const ox = (VIEW - targetW) / 2 - minX * s;
const oy = (VIEW - h) / 2 + maxY * s; // baseline position (y flipped)

const r = (n) => Math.round(n * 100) / 100;
const d = parts
  .map((p) => p.path.transform(s, 0, 0, -s, ox + p.x * s, oy).toSVG())
  .join(" ")
  .replace(/-?\d+\.\d+/g, (m) => String(r(Number(m))));

const gx1 = r((VIEW - targetW) / 2), gx2 = r((VIEW + targetW) / 2), gy = r(VIEW / 2);
const items = COLORS.map((c, i) => `                <item android:offset="${(i / (COLORS.length - 1)).toFixed(2)}" android:color="${c.toUpperCase()}" />`).join("\n");

const fg = `<?xml version="1.0" encoding="utf-8"?>
<!-- Adaptive icon foreground: the DioTa wordmark (Fraunces glyph outlines, brand colours).
     Generated by scripts/make-android-icon.mjs. Safe zone is the centre 66dp. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="${VIEW}"
    android:viewportHeight="${VIEW}">
    <path android:pathData="${d}">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="${gx1}"
                android:startY="${gy}"
                android:endX="${gx2}"
                android:endY="${gy}">
${items}
            </gradient>
        </aapt:attr>
    </path>
</vector>
`;
const mono = `<?xml version="1.0" encoding="utf-8"?>
<!-- Themed (monochrome) launcher icon: the DioTa wordmark. Generated by scripts/make-android-icon.mjs. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="${VIEW}"
    android:viewportHeight="${VIEW}">
    <path
        android:fillColor="#FFFFFFFF"
        android:pathData="${d}" />
</vector>
`;
const res = path.join(root, "android/app/src/main/res/drawable");
fs.writeFileSync(path.join(res, "ic_launcher_foreground.xml"), fg);
fs.writeFileSync(path.join(res, "ic_launcher_monochrome.xml"), mono);

const svgOut = process.argv.indexOf("--svg");
if (svgOut > 0) {
  const stops = COLORS.map((c, i) => `<stop offset="${i / (COLORS.length - 1)}" stop-color="${c}"/>`).join("");
  fs.writeFileSync(
    process.argv[svgOut + 1],
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${VIEW} ${VIEW}" width="432" height="432"><defs><linearGradient id="g" gradientUnits="userSpaceOnUse" x1="${gx1}" y1="${gy}" x2="${gx2}" y2="${gy}">${stops}</linearGradient><clipPath id="c"><circle cx="54" cy="54" r="54"/></clipPath></defs><g clip-path="url(#c)"><rect width="108" height="108" fill="#ffffff"/><path d="${d}" fill="url(#g)"/></g></svg>`,
  );
}
console.log("icon written", { width: targetW, height: r(h), bytes: d.length });
